-- PLAY_RUN : 플레이 회차
CREATE TABLE PLAY_RUN (
    case_id NUMBER(10) CONSTRAINT NN_PLAY_RUN_CASE_ID NOT NULL,
    run_no NUMBER(10) CONSTRAINT NN_PLAY_RUN_RUN_NO NOT NULL,
    started_at TIMESTAMP(0) CONSTRAINT NN_PLAY_RUN_STARTED_AT NOT NULL,
    ended_at TIMESTAMP(0),
    run_status VARCHAR2(7 CHAR) CONSTRAINT NN_PLAY_RUN_RUN_STATUS NOT NULL,
    exit_area_no NUMBER(10),
    ending_no NUMBER(10),
    CONSTRAINT PK_PLAY_RUN PRIMARY KEY (case_id, run_no),
    CONSTRAINT CK_RUN_NO CHECK (run_no >= 1),
    CONSTRAINT CK_RUN_TIME CHECK (ended_at IS NULL OR ended_at >= started_at),
    CONSTRAINT CK_RUN_STATE CHECK ((run_status = 'ACTIVE' AND ended_at IS NULL AND exit_area_no IS NULL AND ending_no IS NULL) OR (run_status = 'FAILED' AND ended_at IS NOT NULL AND exit_area_no IS NULL AND ending_no IS NULL) OR (run_status = 'ESCAPED' AND ended_at IS NOT NULL AND exit_area_no IS NOT NULL AND ending_no IS NOT NULL)),
    CONSTRAINT CK_PLAY_RUN_RUN_STATUS CHECK (run_status IN ('ACTIVE','ESCAPED','FAILED')),
    CONSTRAINT FK_PLAY_RUN_CASE FOREIGN KEY (case_id)
        REFERENCES CASE_FILE (case_id),
    CONSTRAINT FK_PLAY_RUN_EXIT_AREA FOREIGN KEY (case_id, exit_area_no)
        REFERENCES AREA (case_id, area_no),
    CONSTRAINT FK_PLAY_RUN_ENDING FOREIGN KEY (case_id, ending_no)
        REFERENCES ENDING (case_id, ending_no)
);

COMMENT ON TABLE PLAY_RUN IS '플레이 회차';

COMMENT ON COLUMN PLAY_RUN.case_id IS '플레이한 사건';

