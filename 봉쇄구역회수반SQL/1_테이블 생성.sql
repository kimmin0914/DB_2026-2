COMMENT ON COLUMN PUZZLE.prompt IS '문제와 입력 방식';

COMMENT ON COLUMN PUZZLE.answer_key IS '정규화한 정답';

COMMENT ON COLUMN PUZZLE.hint_text IS '요청 시 보여줄 힌트';

COMMENT ON COLUMN PUZZLE.solved_text IS '해결 후 대사와 안내';

